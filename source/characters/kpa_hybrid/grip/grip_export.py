# grips.json -> EnemyGrips.cs (the table the game holds the rifle by)
import json

OUT = r'C:\team\five_river\Assets\_Project\Scripts\Combat\EnemyGrips.cs'
res = json.load(open('C:/sk_assets/capture/grip/grips.json'))
f = lambda v: ('%.6f' % v).rstrip('0').rstrip('.') + 'f'
out = ['// Generated by source/characters/kpa_hybrid/grip/grip_export.py - do not edit by hand, solve again instead.',
       'using UnityEngine;', '',
       'namespace FiveRivers.Combat',
       '{',
       '    // How the KPA rifleman holds the Mosin (2026-11-22). Each hold was solved offline from the real meshes: no skin',
       '    // in the rifle, palm and fingertips on it, the wrist within what a wrist bends, the fingers not in one another.',
       '    // Wrist and Turn: the hand bone in the rifle\'s space. Elbow: the way it points, in the animator\'s axes.',
       '    // Fingers: local rotations - thumb, index, middle, ring, little, three joints each.',
       '    static class EnemyGrips',
       '    {',
       '        public sealed class Hold',
       '        {',
       '            public readonly Vector3 Wrist, Elbow;',
       '            public readonly Quaternion Turn;',
       '            public readonly Quaternion[] Fingers;',
       '            public Hold(Vector3 wrist, Quaternion turn, Vector3 elbow, Quaternion[] fingers)',
       '            { Wrist = wrist; Turn = turn; Elbow = elbow; Fingers = fingers; }',
       '        }']
for name in ('RightCarry', 'RightAim', 'LeftLow', 'LeftRun', 'LeftKneel', 'LeftStand'):
    g = res[name]
    out += ['',
            '        // wrist bent %+.0f, sideways %+.0f degrees' % (g['flex'], g['dev']),
            '        public static readonly Hold %s = new Hold(' % name,
            '            new Vector3(%s), new Quaternion(%s),' % (', '.join(map(f, g['pos'])), ', '.join(map(f, g['rot']))),
            '            new Vector3(%s), new[]' % ', '.join(map(f, g['elbow'])),
            '            {']
    out += ['                new Quaternion(%s),' % ', '.join(map(f, q)) for q in g['joints']]
    out += ['            });']
out += ['    }', '}', '']
open(OUT, 'w', encoding='utf-8', newline='\r\n').write('\n'.join(out))
print('WROTE', OUT)
